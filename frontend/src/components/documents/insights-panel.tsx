"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { AlertCircle, ExternalLink, Info, RefreshCw, Sparkles } from "lucide-react";
import Link from "next/link";
import { toast } from "sonner";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { errorMessage } from "@/lib/api";
import { formatDateTime } from "@/lib/format";
import { insightsService, type Finding, type InsightPayload, type Structure } from "@/services/insights";

function EvidenceLink({ docId, f }: { docId: string; f: Finding }) {
  if (!f.page) return null;
  const href = `/documents/${docId}/view?page=${f.page}${f.quote ? `&hl=${encodeURIComponent(f.quote)}` : ""}`;
  return (
    <Link href={href} className="ml-1 inline-flex items-center gap-0.5 whitespace-nowrap text-xs text-primary hover:underline" aria-label={`Open page ${f.page} in the viewer`}>
      p.{f.page} <ExternalLink className="size-3" aria-hidden />
    </Link>
  );
}

function FindingList({ title, items, docId }: { title: string; items: Finding[]; docId: string }) {
  if (!items.length) return null;
  return (
    <section>
      <h3 className="mb-1.5 text-sm font-semibold">{title}</h3>
      <ul className="space-y-2 text-sm">
        {items.map((f, i) => (
          <li key={i}>
            {f.text}
            <EvidenceLink docId={docId} f={f} />
            {f.quote && <blockquote className="mt-0.5 border-l-2 pl-2 text-xs text-muted-foreground">&ldquo;{f.quote}&rdquo;</blockquote>}
          </li>
        ))}
      </ul>
    </section>
  );
}

function Chips({ title, items }: { title: string; items: string[] }) {
  if (!items.length) return null;
  return (
    <section>
      <h3 className="mb-1.5 text-sm font-semibold">{title}</h3>
      <div className="flex flex-wrap gap-1.5">{items.map((t) => <Badge key={t} variant="secondary">{t}</Badge>)}</div>
    </section>
  );
}

export function InsightsPanel({ workspaceId, documentId, canEdit }: { workspaceId: string; documentId: string; canEdit: boolean }) {
  const qc = useQueryClient();
  const q = useQuery({
    queryKey: ["insights", workspaceId, documentId],
    queryFn: () => insightsService.get(workspaceId, documentId),
    refetchInterval: (query) => (["pending", "running"].includes(query.state.data?.status ?? "") ? 2500 : false),
  });
  const regen = useMutation({
    mutationFn: () => insightsService.regenerate(workspaceId, documentId),
    onSuccess: () => {
      toast.success("Generating insights…");
      qc.invalidateQueries({ queryKey: ["insights", workspaceId, documentId] });
    },
    onError: (e) => toast.error(errorMessage(e)),
  });

  const d = q.data;
  const p = d?.payload as InsightPayload | null | undefined;
  const s = d?.structure as Structure | null | undefined;

  return (
    <Card className="lg:col-span-3">
      <CardHeader className="flex-row items-start justify-between gap-3">
        <div>
          <CardTitle className="flex items-center gap-2"><Sparkles className="size-4 text-primary" aria-hidden /> AI insights</CardTitle>
          <CardDescription>
            Generated by AI from this document. Quotes and page numbers are checked against the extracted text; verify important details in the source.
            {d?.generated_at && ` Updated ${formatDateTime(d.generated_at)}.`}
          </CardDescription>
        </div>
        {canEdit && (d?.status === "completed" || d?.status === "failed") && (
          <Button variant="outline" size="sm" disabled={regen.isPending} onClick={() => regen.mutate()}>
            <RefreshCw className="size-3.5" aria-hidden /> Regenerate
          </Button>
        )}
      </CardHeader>
      <CardContent>
        {q.isLoading ? (
          <div className="space-y-2"><Skeleton className="h-5 w-2/3" /><Skeleton className="h-20" /></div>
        ) : q.isError ? (
          <p role="alert" className="text-sm text-destructive">{errorMessage(q.error)}</p>
        ) : d?.status === "pending" || d?.status === "running" ? (
          <div role="status" className="space-y-2" aria-live="polite">
            <p className="text-sm text-muted-foreground">Analysing the document…</p>
            <Skeleton className="h-5 w-2/3" /><Skeleton className="h-20" />
          </div>
        ) : d?.status === "unavailable" ? (
          <p role="status" className="flex items-start gap-2 text-sm text-muted-foreground"><Info className="mt-0.5 size-4 shrink-0" aria-hidden /> {d.error}</p>
        ) : d?.status === "failed" ? (
          <p role="alert" className="flex items-start gap-2 text-sm text-destructive"><AlertCircle className="mt-0.5 size-4 shrink-0" aria-hidden /> Insights could not be generated: {d.error}</p>
        ) : d?.status === "none" ? (
          <div className="flex items-center justify-between gap-3 text-sm text-muted-foreground">
            <span>No insights yet.</span>
            {canEdit && <Button size="sm" disabled={regen.isPending} onClick={() => regen.mutate()}>Generate insights</Button>}
          </div>
        ) : p ? (
          <div className="grid gap-6 md:grid-cols-2">
            <div className="space-y-5">
              <section>
                <h3 className="mb-1.5 text-sm font-semibold">Executive summary</h3>
                <p className="text-sm">{p.executive_summary}</p>
              </section>
              <section>
                <h3 className="mb-1.5 text-sm font-semibold">Summary</h3>
                <p className="whitespace-pre-wrap text-sm text-muted-foreground">{p.summary}</p>
              </section>
              <FindingList title="Key findings" items={p.key_findings} docId={documentId} />
              <FindingList title="Important facts" items={p.key_facts} docId={documentId} />
              <FindingList title="Main arguments" items={p.main_arguments} docId={documentId} />
              <FindingList title="Conclusions" items={p.conclusions} docId={documentId} />
              <FindingList title="Limitations" items={p.limitations} docId={documentId} />
              {p.action_items.length > 0 && (
                <section>
                  <h3 className="mb-1.5 text-sm font-semibold">Action items</h3>
                  <ul className="list-disc space-y-1 pl-5 text-sm">{p.action_items.map((a, i) => <li key={i}>{a}</li>)}</ul>
                </section>
              )}
            </div>
            <div className="space-y-5">
              <section>
                <h3 className="mb-1.5 text-sm font-semibold">Classification</h3>
                <p className="text-sm">
                  {p.classification.document_type} · {p.classification.category}{" "}
                  <span className="text-xs text-muted-foreground">({p.classification.confidence} confidence)</span>
                </p>
              </section>
              <Chips title="Topics" items={p.topics} />
              <Chips title="Keywords" items={p.keywords} />
              <Chips title="People" items={p.entities.people} />
              <Chips title="Organizations" items={p.entities.organizations} />
              <Chips title="Locations" items={p.entities.locations} />
              {p.important_dates.length > 0 && (
                <section>
                  <h3 className="mb-1.5 text-sm font-semibold">Important dates</h3>
                  <ul className="space-y-1 text-sm">
                    {p.important_dates.map((x, i) => (
                      <li key={i}><span className="font-medium">{x.date}</span> {x.description}{x.page ? <EvidenceLink docId={documentId} f={{ text: "", page: x.page, quote: null }} /> : null}</li>
                    ))}
                  </ul>
                </section>
              )}
              {s && s.outline.length > 0 && (
                <section>
                  <h3 className="mb-1.5 text-sm font-semibold">Structure</h3>
                  <ol className="space-y-0.5 text-sm">
                    {s.outline.slice(0, 40).map((h, i) => (
                      <li key={i} style={{ paddingLeft: `${(h.level - 1) * 12}px` }}>
                        <Link href={`/documents/${documentId}/view?page=${h.page}`} className="hover:underline">{h.title}</Link>
                        <span className="ml-1 text-xs text-muted-foreground">p.{h.page}</span>
                      </li>
                    ))}
                  </ol>
                </section>
              )}
              {s && s.tables.length > 0 && (
                <section>
                  <h3 className="mb-1.5 text-sm font-semibold">Tables ({s.tables.length})</h3>
                  <ul className="space-y-1 text-sm">
                    {s.tables.slice(0, 20).map((t, i) => (
                      <li key={i}>
                        <Link href={`/documents/${documentId}/view?page=${t.page}`} className="hover:underline">Page {t.page}</Link>
                        <span className="ml-1 text-xs text-muted-foreground">{t.rows} rows × {t.columns} columns</span>
                      </li>
                    ))}
                  </ul>
                </section>
              )}
              {d?.verification && (d.verification.dropped_quotes > 0 || d.verification.dropped_pages > 0) && (
                <p className="text-xs text-muted-foreground">
                  {d.verification.dropped_quotes} unverifiable quote(s) and {d.verification.dropped_pages} invalid page reference(s) were removed.
                </p>
              )}
            </div>
          </div>
        ) : null}
      </CardContent>
    </Card>
  );
}
